def _查一项(值, 允许):
    """返回错误说明；没错返回 None。"""
    if 允许 is None:
        return None
    if isinstance(允许, tuple):
        try:
            命中 = 值 in 允许
        except TypeError:
            命中 = False
        if not 命中:
            return "只能是 %s 之一，收到 %r" % ("/".join(map(str, 允许)), 值)
        return None
    if isinstance(允许, type):
        if not isinstance(值, 允许):
            return "应为 %s，收到 %s" % (允许.__name__, type(值).__name__)
        return None
    if callable(允许):                    # 自定义校验规则（目前只有 时间戳）
        if not 允许(值):
            return "格式不对，收到 %r" % (值,)
        return None
    return None


def 校验(名字, 对象, 路径="$"):
    """
    按规格表查一个对象。返回错误清单（空 = 通过）。

    故意做成「返回清单」而不是「抛异常」——因为调用方是 HTTP 层，
    它需要把错误原样回给前端，而不是崩掉。
    """
    规格 = 规格表.get(名字)
    if 规格 is None:
        return ["%s：没有这个规格（有的是 %s）" % (名字, "、".join(规格表))]

    错 = []
    if not isinstance(对象, dict):
        return ["%s：应为对象，收到 %s" % (路径, type(对象).__name__)]

    for 字段, (必填, 允许, _说明) in 规格.items():
        if 字段 not in 对象 or 对象[字段] is None:
            if 必填:
                错.append("%s.%s：必填，缺了" % (路径, 字段))
            continue
        e = _查一项(对象[字段], 允许)
        if e:
            错.append("%s.%s：%s" % (路径, 字段, e))

    # 卡点：子类只有「隐含条件未说出」能填。[源: §3.2·S12 续]
    if 名字 == "卡点" and 对象.get("子类") and 对象.get("类型") != "隐含条件未说出":
        错.append("%s.子类：只有「隐含条件未说出」才有子类" % 路径)

    # 卡点：步骤必须和类型对得上。[推断，见 _卡点归属步骤]
    if 名字 == "卡点" and 对象.get("类型") in _卡点归属步骤:
        if 对象.get("步骤") and 对象["步骤"] not in _卡点归属步骤[对象["类型"]]:
            错.append("%s.步骤：%s 只可能落在 %s"
                      % (路径, 对象["类型"], "/".join(_卡点归属步骤[对象["类型"]])))

    # 条件句必须有级别；非条件句不该有。[源: §4.1·F5「只对判为条件句的句子提问」]
    if 名字 == "分句":
        if 对象.get("type") == "条件" and not 对象.get("level"):
            错.append("%s.level：条件句必须有级别" % 路径)
        if 对象.get("type") and 对象.get("type") != "条件" and 对象.get("level"):
            错.append("%s.level：只有条件句才有级别" % 路径)

    return 错


def 校验练习记录(记录):
    """练习记录是个复合对象，要连里面的 卡点 / 错题 / 错题里的错在哪 一起查。"""
    错 = 校验("练习记录", 记录)
    if isinstance(记录, dict):
        for n, 卡点 in enumerate(记录.get("卡点") or []):
            错 += 校验("卡点", 卡点, "$.卡点[%d]" % n)
        for n, 错题 in enumerate(记录.get("错题") or []):
            前缀 = "$.错题[%d]" % n
            错 += 校验("错题项", 错题, 前缀)
            if isinstance(错题, dict):
                # 「错在哪」里装的也是卡点，所以照样按卡点的规格查一遍
                for m, 卡 in enumerate(错题.get("错在哪") or []):
                    错 += 校验("卡点", 卡, "%s.错在哪[%d]" % (前缀, m))
    return 错


