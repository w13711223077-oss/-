def 时间戳(值):
    """
    校验规则：ISO 8601，而且**必须带时区**。

    为什么必须带时区：服务端算「总时长」是拿开始时间减结束时间。
    naive 和 aware 相减抛的是 TypeError（不是 ValueError），
    所以在门口就拦住，别让它走到存储层才炸。
    """
    try:
        return _datetime.fromisoformat(值).tzinfo is not None
    except (ValueError, TypeError):
        return False


