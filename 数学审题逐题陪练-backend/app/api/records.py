#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
端点组② —— 存记录 / 读记录 / 未清账目
================================================================================

【这一组是选 A 的全部理由。】
§8.2 那行红字：「F14 建错题库，指向『要有存储』——而 v1 是 HTML、无后端。这是硬冲突。」
不选 A，F14 就永远只是设计，不是功能。

四个入口：
  POST /api/v1/exercises            写一次练习（S12 落库：错题库 + 卡点记录库）
  GET  /api/v1/exercises            读练习记录
  GET  /api/v1/pending              未清账目 —— 第九节 #2「重练的入口」
  POST /api/v1/wrong-items/done     把一道错题标记为「重做过了」

依赖：只用 Python 标准库。
"""

from ..domain import schema
from ..store import jsonl_store as 库


# ─────────────────────────────────────────────────────────────
# POST /api/v1/exercises —— S12 落库
# ─────────────────────────────────────────────────────────────

def 写记录(请求体, _查询):
    """
    入参：一条「练习记录」（字段见 GET /api/v1/schema）
    出参：落库后的记录

    校验不过就退回 422，并**把每一条错在哪都说清楚**——
    这个接口的调用方是前端的 S12，出错时前端要能提示到具体字段。
    """
    错 = schema.校验练习记录(请求体)
    if 错:
        return 422, {"错误": "练习记录不合契约", "明细": 错,
                     "提示": "字段口径见 GET /api/v1/schema"}

    记录 = 库.存练习(请求体)
    return 201, {
        "练习ID": 记录["练习ID"],
        "已写入": {
            "练习记录": 1,
            "卡点记录库": len(记录.get("卡点") or []),
            "错题库": len(记录.get("错题") or []),
        },
        "记录": 记录,
    }


# ─────────────────────────────────────────────────────────────
# GET /api/v1/exercises —— 读练习记录
# ─────────────────────────────────────────────────────────────

def 读记录(_请求体, 查询):
    """
    入参（URL 查询串，都可选）：
      ?练习ID=EX-xxxx   只要这一次
      ?limit=20         最近几条（默认 20，最大 200）
    """
    全部 = 库.读全部(库.练习库)
    练习ID = (查询.get("练习ID") or "").strip()
    if 练习ID:
        全部 = [x for x in 全部 if x.get("练习ID") == 练习ID]

    try:
        limit = int(查询.get("limit") or 20)
    except ValueError:
        return 400, {"错误": "limit 要是整数"}
    limit = max(1, min(limit, 200))

    return 200, {"条数": len(全部), "返回": min(limit, len(全部)),
                 "记录": 全部[-limit:]}


# ─────────────────────────────────────────────────────────────
# GET /api/v1/pending —— 未清账目（重练的入口）
# ─────────────────────────────────────────────────────────────

def 未清账目(_请求体, _查询):
    """
    §3.2·S12：「把产品的使用从『卡住时打开一次』变成『有没清完的账，就回来』。」

    第九节 #2 说得很直白：**没有任何入口，「重练」就只是纸上的功能。**
    这个端点就是那个入口——它只回答一个问题：**还有什么没清？**
    """
    账 = 库.未清账目()
    账["_来源"] = "§3.2·S12 / §9·#2"
    return 200, 账


# ─────────────────────────────────────────────────────────────
# POST /api/v1/wrong-items/done —— 清一笔账
# ─────────────────────────────────────────────────────────────

def 标记已重做(请求体, _查询):
    """
    入参：{"题ID": "WI-xxxx"}
    出参：{"题ID": ..., "已重做": true}
    """
    题ID = (请求体.get("题ID") or "").strip()
    if not 题ID:
        return 400, {"错误": "缺少 题ID"}
    if not 库.标记已重做(题ID):
        return 404, {"错误": "错题库里没有这道题：%s" % 题ID}
    return 200, {"题ID": 题ID, "已重做": True}


# ─────────────────────────────────────────────────────────────
# 路由表（main.py 读它）
# ─────────────────────────────────────────────────────────────
路由 = [
    ("POST", "/api/v1/exercises", 写记录),
    ("GET", "/api/v1/exercises", 读记录),
    ("GET", "/api/v1/pending", 未清账目),
    ("POST", "/api/v1/wrong-items/done", 标记已重做),
]
